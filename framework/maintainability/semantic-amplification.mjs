const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);
const MANIFEST_PATH =
  'framework/maintainability/semantic-amplification.manifest.json';
const TERMINAL_MATRIX_PATH =
  'framework/maintainability/terminal-evidence-matrix.json';
const ALLOWED_STATES = new Set([
  'proved',
  'partial',
  'missing',
  'invalidated',
  'retained-dependency',
]);
const INTEGRITY_DETECTORS = new Set([
  'line-count',
  'normalized-line-overlap',
  'token-spread',
]);
const ELECTRON_BUILDER_PROJECTION_PATHS = {
  framework: path.join(ROOT, 'framework', 'gui', 'electron-builder.yml'),
  product: path.join(ROOT, 'product', 'electron-builder.yml'),
};

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function deepOverlay(base, overlay) {
  const result = clone(base);
  for (const [key, value] of Object.entries(overlay)) {
    if (isObject(value) && isObject(result[key])) {
      result[key] = deepOverlay(result[key], value);
    } else {
      result[key] = clone(value);
    }
  }
  return result;
}

function resourceKey(resource) {
  return JSON.stringify([resource.from ?? '.', resource.to ?? '.']);
}

function mergeExtraResources(base, overlay, removed) {
  const removedKeys = new Set(removed.map(resourceKey));
  const overlayByKey = new Map(
    overlay.map((resource) => [resourceKey(resource), clone(resource)]),
  );
  const merged = [];
  for (const resource of base) {
    const key = resourceKey(resource);
    if (removedKeys.has(key)) continue;
    merged.push(overlayByKey.get(key) ?? clone(resource));
    overlayByKey.delete(key);
  }
  merged.push(...overlayByKey.values());
  return merged;
}

function materializeElectronBuilderConfigs() {
  const base = readJson('framework/gui/electron-builder.base.json');
  const overlayEnvelope = readJson('product/electron-builder.overlay.json');
  const overlay = overlayEnvelope.config;
  const { extraResources: overlayResources, ...overlayWithoutResources } =
    overlay;
  const product = deepOverlay(base, overlayWithoutResources);
  product.extraResources = mergeExtraResources(
    base.extraResources,
    overlayResources,
    overlayEnvelope.removeExtraResources,
  );
  return {
    framework: clone(base),
    product,
  };
}

function serializeElectronBuilderProjection(name, config) {
  return [
    `# Generated by framework/maintainability/semantic-amplification.mjs from the canonical base and ${name} overlay.`,
    '# Run: node framework/maintainability/semantic-amplification.mjs --electron-builder-config-write',
    JSON.stringify(config, null, 2),
    '',
  ].join('\n');
}

function expectedElectronBuilderProjections() {
  const configs = materializeElectronBuilderConfigs();
  return {
    framework: serializeElectronBuilderProjection(
      'framework',
      configs.framework,
    ),
    product: serializeElectronBuilderProjection('product', configs.product),
  };
}

function readElectronBuilderProjection(projectionPath) {
  return JSON.parse(
    fs
      .readFileSync(projectionPath, 'utf8')
      .split('\n')
      .filter((line) => !line.startsWith('#'))
      .join('\n'),
  );
}

function checkElectronBuilderProjections() {
  const expected = expectedElectronBuilderProjections();
  const drift = Object.entries(ELECTRON_BUILDER_PROJECTION_PATHS)
    .filter(([name, projectionPath]) => {
      try {
        return fs.readFileSync(projectionPath, 'utf8') !== expected[name];
      } catch {
        return true;
      }
    })
    .map(([name]) => name);
  if (drift.length > 0) {
    throw new Error(
      `electron_builder_projection_drift:${drift.join(',')}; run node framework/maintainability/semantic-amplification.mjs --electron-builder-config-write`,
    );
  }
}

function writeElectronBuilderProjections() {
  const expected = expectedElectronBuilderProjections();
  for (const [name, projectionPath] of Object.entries(
    ELECTRON_BUILDER_PROJECTION_PATHS,
  )) {
    fs.writeFileSync(projectionPath, expected[name]);
  }
}

function allFamilyPaths(family) {
  return [
    ...family.authority.sources,
    ...family.surfaces.map((surface) => surface.path),
  ];
}

function measurePath(relative, baselineRef, changed) {
  const current = currentBytes(relative);
  let baseline = null;
  try {
    baseline = baselineBytes(baselineRef, relative);
  } catch {
    baseline = null;
  }
  return {
    path: relative,
    currentLines: lines(current),
    baselineLines: baseline ? lines(baseline) : null,
    currentRoot: digest(current),
    baselineRoot: baseline ? digest(baseline) : null,
    changedSinceBaseline: changed.has(relative),
  };
}

function issue(code, family, target, message) {
  return { code, family, target, message };
}

function integrityFinding({
  findingClass,
  topology,
  target,
  message,
  evidence = {},
  detector = '',
}) {
  return {
    id: [topology, detector || findingClass].filter(Boolean).join(':'),
    class: findingClass,
    topology,
    target,
    message,
    evidence,
  };
}

function defaultIntegrityIo() {
  return {
    exists: (relative) => fs.existsSync(path.join(ROOT, relative)),
    readText: (relative) => fs.readFileSync(path.join(ROOT, relative), 'utf8'),
    now: () => new Date(),
  };
}

function normalizedLines(text, minimumLength = 4) {
  return new Set(
    String(text)
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter(
        (line) =>
          line.length >= minimumLength &&
          !line.startsWith('#') &&
          !line.startsWith('//'),
      ),
  );
}

function evaluateDetector(topology, detector, io) {
  const paths = detector.paths || [];
  let metric = null;
  let threshold = null;
  let findingInput = null;
  if (detector.kind === 'line-count') {
    const path = paths[0];
    metric = lines(Buffer.from(io.readText(path)));
    threshold = detector.maximum;
    findingInput = {
      findingClass: detector.findingClass,
      topology: topology.id,
      target: path,
      detector: detector.id,
      message: `${path} has ${metric} lines; the governed maximum is ${threshold}`,
      evidence: { lineCount: metric, maximum: threshold },
    };
  } else if (detector.kind === 'normalized-line-overlap') {
    const [leftPath, rightPath] = paths;
    const left = normalizedLines(
      io.readText(leftPath),
      detector.minimumLineLength,
    );
    const right = normalizedLines(
      io.readText(rightPath),
      detector.minimumLineLength,
    );
    const shared = [...left].filter((line) => right.has(line)).sort();
    metric = shared.length;
    threshold = detector.maximumSharedLines;
    findingInput = {
      findingClass: detector.findingClass,
      topology: topology.id,
      target: paths.join(','),
      detector: detector.id,
      message: `${metric} normalized policy lines are duplicated across ${paths.join(' and ')}`,
      evidence: {
        sharedLineCount: metric,
        maximumSharedLines: threshold,
        sample: shared.slice(0, 12),
      },
    };
  } else if (detector.kind === 'token-spread') {
    const matchedPaths = paths
      .map((relative) => {
        const text = io.readText(relative);
        const tokens = (detector.tokens || []).filter((token) =>
          text.includes(token),
        );
        return { path: relative, tokens };
      })
      .filter(({ tokens }) => tokens.length > 0);
    metric = matchedPaths.length;
    threshold = detector.maximumPaths;
    findingInput = {
      findingClass: detector.findingClass,
      topology: topology.id,
      target: paths.join(','),
      detector: detector.id,
      message: `${metric} files carry the same platform primitive family; the governed maximum is ${threshold}`,
      evidence: {
        matchedPaths,
        maximumPaths: threshold,
      },
    };
  } else {
    return {
      detector: detector.id,
      topology: topology.id,
      kind: detector.kind,
      status: 'invalid',
      metric: null,
      threshold: null,
      finding: integrityFinding({
        findingClass: 'policy-drift',
        topology: topology.id,
        target: detector.id || topology.id,
        detector: detector.id,
        message: `unknown integrity detector '${detector.kind}'`,
      }),
    };
  }

  const isFinding = metric > threshold;
  return {
    detector: detector.id,
    topology: topology.id,
    kind: detector.kind,
    status: isFinding ? 'finding' : 'remediated',
    metric,
    threshold,
    finding: isFinding ? integrityFinding(findingInput) : null,
  };
}

function evaluateIntegrity(policy, io = defaultIntegrityIo()) {
  if (!policy) {
    return null;
  }
  const findings = [];
  const outcomes = [];
  const classes = policy.findingClasses || {};
  const now = io.now();
  for (const topology of policy.topologies || []) {
    for (const authority of topology.additionalAuthorities || []) {
      findings.push(
        integrityFinding({
          findingClass: 'parallel-authority',
          topology: topology.id,
          target: authority.id || topology.id,
          message: 'topology declares an additional business authority',
          evidence: { authority },
        }),
      );
    }
    const adapters = topology.adapters || [];
    const adapterIds = new Set();
    const adapterSignatures = new Map();
    for (const adapter of adapters) {
      if (!adapter.id || adapterIds.has(adapter.id)) {
        findings.push(
          integrityFinding({
            findingClass: 'duplicate-policy',
            topology: topology.id,
            target: adapter.id || topology.id,
            message: 'adapter ids must be present and unique',
          }),
        );
      }
      adapterIds.add(adapter.id);
      if (!adapter.authorityBinding) {
        findings.push(
          integrityFinding({
            findingClass: 'orphan-adapter',
            topology: topology.id,
            target: adapter.id || topology.id,
            message: 'adapter has no declared authority binding',
          }),
        );
      }
      for (const [axis, value] of Object.entries(adapter.axes || {})) {
        if (!(topology.legalAxes?.[axis] || []).includes(value)) {
          findings.push(
            integrityFinding({
              findingClass: 'illegal-axis-value',
              topology: topology.id,
              target: adapter.id || topology.id,
              message: `adapter axis ${axis}=${value} is outside the declared legal topology`,
              evidence: {
                axis,
                value,
                legalValues: topology.legalAxes?.[axis] || [],
              },
            }),
          );
        }
      }
      const signature = JSON.stringify(
        ordered({
          axes: adapter.axes || {},
          paths: adapter.paths || [],
        }),
      );
      if (adapterSignatures.has(signature)) {
        findings.push(
          integrityFinding({
            findingClass: 'duplicate-policy',
            topology: topology.id,
            target: adapter.id || topology.id,
            message: `adapter duplicates ${adapterSignatures.get(signature)} without a distinct variant`,
          }),
        );
      } else {
        adapterSignatures.set(signature, adapter.id);
      }
    }
    if (!(topology.qualification || []).length) {
      findings.push(
        integrityFinding({
          findingClass: 'missing-qualification',
          topology: topology.id,
          target: topology.id,
          message: 'topology has no independent qualification route',
        }),
      );
    }
    for (const exception of topology.exceptions || []) {
      const expiresAt = new Date(exception.expiresAt || '');
      if (
        !exception.rationale ||
        !exception.remediation ||
        !Number.isFinite(expiresAt.getTime()) ||
        expiresAt <= now
      ) {
        findings.push(
          integrityFinding({
            findingClass: 'stale-exception',
            topology: topology.id,
            target: exception.id || topology.id,
            message: 'exception is expired or lacks rationale/remediation',
            evidence: { expiresAt: exception.expiresAt || null },
          }),
        );
      }
    }
    for (const detector of topology.detectors || []) {
      if ((detector.paths || []).every((relative) => io.exists(relative))) {
        const outcome = evaluateDetector(topology, detector, io);
        outcomes.push(outcome);
        if (outcome.finding) findings.push(outcome.finding);
      }
    }
  }
  const weightedDebt = findings.reduce(
    (total, finding) => total + Number(classes[finding.class]?.weight || 0),
    0,
  );
  const metrics = {
    topologies: (policy.topologies || []).length,
    legalAxes: (policy.topologies || []).reduce(
      (total, topology) => total + Object.keys(topology.legalAxes || {}).length,
      0,
    ),
    adapters: (policy.topologies || []).reduce(
      (total, topology) => total + (topology.adapters || []).length,
      0,
    ),
    projections: (policy.topologies || []).reduce(
      (total, topology) => total + (topology.projections || []).length,
      0,
    ),
    qualificationRoutes: (policy.topologies || []).reduce(
      (total, topology) => total + (topology.qualification || []).length,
      0,
    ),
    exceptionDebt: (policy.topologies || []).reduce(
      (total, topology) => total + (topology.exceptions || []).length,
      0,
    ),
    findings: findings.length,
    weightedDebt,
  };
  const baseline = policy.ratchet?.baseline || {};
  return {
    schema: 'kungfu.abstraction-integrity-report/v1',
    authoritySemantics: 'additive-governance-over-declared-authorities',
    dimensions: policy.dimensions,
    metrics,
    baseline,
    baselineComparison: {
      findingDelta: metrics.findings - Number(baseline.findings || 0),
      weightedDebtDelta:
        metrics.weightedDebt - Number(baseline.weightedDebt || 0),
      ratchet:
        metrics.weightedDebt <= Number(baseline.weightedDebt || 0)
          ? 'pass'
          : 'regressed',
    },
    topologies: policy.topologies,
    detectorOutcomes: outcomes,
    findings,
  };
}

function validateManifest(
  manifest,
  layers,
  changed,
  terminalMatrix = readJson(TERMINAL_MATRIX_PATH),
) {
  const issues = [];
  const allowedRoles = new Set(manifest.rolePolicy.allowedProjectionRoles);
  const ids = new Set();
  for (const family of manifest.families || []) {
    if (!family.id || ids.has(family.id))
      issues.push(
        issue(
          'invalid-family-id',
          family.id || '',
          MANIFEST_PATH,
          'family ids must be present and unique',
        ),
      );
    ids.add(family.id);
    if (
      !family.authority ||
      !family.authority.id ||
      !Array.isArray(family.authority.sources) ||
      family.authority.sources.length === 0
    )
      issues.push(
        issue(
          'missing-authority',
          family.id,
          MANIFEST_PATH,
          'family must bind exactly one authority route with source files',
        ),
      );
    const seen = new Set();
    for (const relative of family.authority?.sources || []) {
      if (seen.has(relative))
        issues.push(
          issue(
            'duplicate-surface',
            family.id,
            relative,
            'path appears more than once in the family',
          ),
        );
      seen.add(relative);
      if (!fs.existsSync(path.join(ROOT, relative)))
        issues.push(
          issue(
            'missing-surface',
            family.id,
            relative,
            'authority source is missing',
          ),
        );
    }
    for (const surface of family.surfaces || []) {
      if (!allowedRoles.has(surface.role))
        issues.push(
          issue(
            'unknown-role',
            family.id,
            surface.path,
            `unknown projection role '${surface.role}'`,
          ),
        );
      if (seen.has(surface.path))
        issues.push(
          issue(
            'duplicate-surface',
            family.id,
            surface.path,
            'path cannot be both authority and projection',
          ),
        );
      seen.add(surface.path);
      if (!fs.existsSync(path.join(ROOT, surface.path)))
        issues.push(
          issue(
            'missing-surface',
            family.id,
            surface.path,
            'projection is missing',
          ),
        );
      if (
        surface.role === 'generated-projection' &&
        surface.generator &&
        !fs.existsSync(path.join(ROOT, surface.generator))
      )
        issues.push(
          issue(
            'missing-generator',
            family.id,
            surface.path,
            `declared generator is missing: ${surface.generator}`,
          ),
        );
    }
    for (const relative of seen) {
      if (!fs.existsSync(path.join(ROOT, relative))) continue;
      const owner = ownerFor(relative, layers);
      if (!owner)
        issues.push(
          issue(
            'unknown-owner',
            family.id,
            relative,
            'surface has no repository measurement owner',
          ),
        );
    }
    const mapped = new Set(seen);
    for (const relative of changed) {
      if (
        mapped.has(relative) ||
        !(family.discoveryRoots || []).some((root) =>
          relative.startsWith(root),
        ) ||
        !fs.existsSync(path.join(ROOT, relative))
      )
        continue;
      const stat = fs.statSync(path.join(ROOT, relative));
      if (!stat.isFile() || stat.size > 8 * 1024 * 1024) continue;
      const text = fs.readFileSync(path.join(ROOT, relative), 'utf8');
      if ((family.identityTokens || []).some((token) => text.includes(token)))
        issues.push(
          issue(
            'unmapped-semantic-surface',
            family.id,
            relative,
            'changed file references this semantic identity but has no declared authority/projection role',
          ),
        );
    }
  }
  for (const boundary of manifest.productionBoundaries || []) {
    if (!ALLOWED_STATES.has(boundary.state))
      issues.push(
        issue(
          'unknown-production-state',
          '',
          boundary.id || MANIFEST_PATH,
          `unknown production boundary state '${boundary.state}'`,
        ),
      );
    for (const relative of boundary.evidence || [])
      if (!fs.existsSync(path.join(ROOT, relative)))
        issues.push(
          issue(
            'missing-boundary-evidence',
            '',
            relative,
            `production boundary ${boundary.id} references missing evidence`,
          ),
        );
    if (boundary.dependentAssignment) {
      const row = (terminalMatrix.rows || []).find(
        ({ assignmentId }) =>
          assignmentId === boundary.dependentAssignment.assignmentId,
      );
      if (!row) {
        issues.push(
          issue(
            'missing-terminal-assignment',
            '',
            boundary.id,
            'projected Assignment is absent from terminal evidence',
          ),
        );
      } else if (row.disposition === 'closed') {
        if (boundary.state !== 'proved') {
          issues.push(
            issue(
              'closed-assignment-projection-conflict',
              '',
              boundary.id,
              `closed Assignment cannot project as '${boundary.state}'`,
            ),
          );
        }
        if (
          boundary.dependentAssignment.requestRoot !==
            row.nativeClosure?.requestRoot ||
          boundary.dependentAssignment.captureReceiptRoot !==
            row.nativeClosure?.captureReceiptRoot ||
          boundary.closureBinding?.sealedStateRoot !==
            terminalMatrix.predecessor?.sealedStateRoot
        ) {
          issues.push(
            issue(
              'terminal-assignment-root-conflict',
              '',
              boundary.id,
              'projected Assignment roots disagree with immutable terminal closure',
            ),
          );
        }
      } else if (boundary.state === 'proved') {
        issues.push(
          issue(
            'projected-closure-without-native-evidence',
            '',
            boundary.id,
            'proved projection requires a closed terminal Assignment row',
          ),
        );
      }
    }
  }
  for (const record of manifest.decompositions || []) {
    for (const relative of [
      ...(record.original || []),
      record.target,
      ...(record.tests || []),
    ].filter(Boolean))
      if (!fs.existsSync(path.join(ROOT, relative)))
        issues.push(
          issue(
            'missing-decomposition-surface',
            '',
            relative,
            `decomposition ${record.id} references a missing path`,
          ),
        );
  }
  const integrity = evaluateIntegrity(manifest.integrityPolicy);
  if (integrity) {
    const dimensions = new Set(manifest.integrityPolicy.dimensions || []);
    const topologyIds = new Set();
    for (const topology of manifest.integrityPolicy.topologies || []) {
      if (!topology.id || topologyIds.has(topology.id))
        issues.push(
          issue(
            'invalid-integrity-topology-id',
            topology.id || '',
            MANIFEST_PATH,
            'integrity topology ids must be present and unique',
          ),
        );
      topologyIds.add(topology.id);
      if (!topology.owner || !topology.authority?.id)
        issues.push(
          issue(
            'missing-integrity-authority',
            topology.id,
            MANIFEST_PATH,
            'integrity topology must declare one owner and one authority',
          ),
        );
      for (const dimension of topology.dimensions || [])
        if (!dimensions.has(dimension))
          issues.push(
            issue(
              'unknown-integrity-dimension',
              topology.id,
              dimension,
              'topology uses a dimension outside the versioned integrity policy',
            ),
          );
      for (const relative of [
        ...(topology.authority?.sources || []),
        ...(topology.adapters || []).flatMap((adapter) => adapter.paths || []),
        ...(topology.projections || []).map(({ path: relative }) => relative),
        ...(topology.qualification || []).map(({ path: relative }) => relative),
        ...(topology.detectors || []).flatMap(
          (detector) => detector.paths || [],
        ),
      ])
        if (!fs.existsSync(path.join(ROOT, relative)))
          issues.push(
            issue(
              'missing-integrity-surface',
              topology.id,
              relative,
              'integrity topology references a missing surface',
            ),
          );
      for (const detector of topology.detectors || [])
        if (!INTEGRITY_DETECTORS.has(detector.kind))
          issues.push(
            issue(
              'unknown-integrity-detector',
              topology.id,
              detector.id || MANIFEST_PATH,
              `unknown detector kind '${detector.kind}'`,
            ),
          );
    }
    for (const finding of integrity.findings)
      if (
        manifest.integrityPolicy.findingClasses?.[finding.class]?.severity ===
        'blocking'
      )
        issues.push(
          issue(
            finding.class,
            finding.topology,
            finding.target,
            finding.message,
          ),
        );
    if (integrity.baselineComparison.ratchet !== 'pass')
      issues.push(
        issue(
          'integrity-ratchet-regression',
          '',
          MANIFEST_PATH,
          `weighted integrity debt ${integrity.metrics.weightedDebt} exceeds baseline ${integrity.baseline.weightedDebt}`,
        ),
      );
  }
  return issues;
}

function buildReport(manifest, layers) {
  const changed = baselineChangedPaths(manifest.baselineRef);
  const terminalMatrix = readJson(TERMINAL_MATRIX_PATH);
  const issues = validateManifest(manifest, layers, changed, terminalMatrix);
  const integrity = evaluateIntegrity(manifest.integrityPolicy);
  const families = manifest.families.map((family) => {
    const measurements = allFamilyPaths(family).map((relative) =>
      measurePath(relative, manifest.baselineRef, changed),
    );
    const roles = {
      authority: family.authority.sources.length,
    };
    for (const surface of family.surfaces)
      roles[surface.role] = (roles[surface.role] || 0) + 1;
    return {
      id: family.id,
      owner: family.owner,
      authority: family.authority,
      authorityCount: 1,
      roles,
      amplification: {
        mappedSurfaces: measurements.length,
        nonAuthoritySurfaces:
          measurements.length - family.authority.sources.length,
        changedSurfaces: measurements.filter(
          (measurement) => measurement.changedSinceBaseline,
        ).length,
        changedPaths: measurements
          .filter((measurement) => measurement.changedSinceBaseline)
          .map((measurement) => measurement.path),
      },
      surfaces: family.surfaces,
      measurements,
      knownLimits: family.knownLimits,
      recovery: family.recovery,
    };
  });
  const mappedRoots = Object.fromEntries(
    families.map((family) => [
      family.id,
      digest(
        family.measurements.map((measurement) => ({
          path: measurement.path,
          root: measurement.currentRoot,
        })),
      ),
    ]),
  );
  const baselineRevision = String(
    git(['rev-parse', `${manifest.baselineRef}^{commit}`]),
  ).trim();
  const body = {
    schema: 'kungfu.semantic-amplification-report/v1',
    verdict: issues.length ? 'fail' : 'pass',
    authoritySemantics: 'navigation-only-projection-over-existing-authorities',
    sourceRevision: String(git(['rev-parse', 'HEAD^{commit}'])).trim(),
    manifestPath: MANIFEST_PATH,
    manifestRoot: digest(manifest),
    generatorRoot: digest(
      currentBytes('framework/maintainability/semantic-amplification.mjs'),
    ),
    baselineRef: manifest.baselineRef,
    baselineRoot: digest({
      ref: manifest.baselineRef,
      revision: baselineRevision,
    }),
    sourceRoot: digest(mappedRoots),
    roles: manifest.rolePolicy,
    summary: {
      families: families.length,
      authorities: families.length,
      mappedSurfaces: families.reduce(
        (total, family) => total + family.amplification.mappedSurfaces,
        0,
      ),
      changedMappedSurfaces: families.reduce(
        (total, family) => total + family.amplification.changedSurfaces,
        0,
      ),
      blockingIssues: issues.length,
    },
    families,
    productionBoundaries: manifest.productionBoundaries,
    terminalEvidenceProjection: {
      matrixPath: TERMINAL_MATRIX_PATH,
      matrixSchema: terminalMatrix.schema,
      predecessorAssignmentId: terminalMatrix.predecessor.assignmentId,
      predecessorSealedStateRoot: terminalMatrix.predecessor.sealedStateRoot,
    },
    decompositions: manifest.decompositions,
    integrity,
    issues,
  };
  return { ...body, reportRoot: digest(body) };
}

function findFamilies(report, manifest, query) {
  const lower = query.toLowerCase();
  const direct = new Set();
  for (const family of manifest.families) {
    if (
      family.id.toLowerCase().includes(lower) ||
      family.identityTokens.some((token) =>
        token.toLowerCase().includes(lower),
      ) ||
      allFamilyPaths(family).some(
        (relative) =>
          relative === query ||
          relative.startsWith(`${query}/`) ||
          query.startsWith(`${relative}/`),
      )
    )
      direct.add(family.id);
  }
  if (direct.size) return [...direct];
  for (const family of manifest.families) {
    for (const relative of allFamilyPaths(family)) {
      const absolute = path.join(ROOT, relative);
      if (
        fs.statSync(absolute).size <= 4 * 1024 * 1024 &&
        fs.readFileSync(absolute, 'utf8').toLowerCase().includes(lower)
      ) {
        direct.add(family.id);
        break;
      }
    }
  }
  return [...direct];
}

function queryTaskGraph(report, manifest, query, layers) {
  const queryLower = query.toLowerCase();
  const ids = findFamilies(report, manifest, query);
  const families = report.families.filter((family) => ids.includes(family.id));
  const pathOwner = fs.existsSync(path.join(ROOT, query))
    ? ownerFor(query, layers)
    : '';
  const integrityTopologies = (report.integrity?.topologies || []).filter(
    (topology) =>
      topology.id.toLowerCase().includes(queryLower) ||
      (topology.dimensions || []).some((dimension) =>
        dimension.toLowerCase().includes(queryLower),
      ) ||
      (topology.adapters || []).some(
        (adapter) =>
          adapter.id.toLowerCase().includes(queryLower) ||
          (adapter.paths || []).some(
            (relative) =>
              relative === query ||
              relative.startsWith(`${query}/`) ||
              query.startsWith(`${relative}/`),
          ),
      ),
  );
  const graphResolved =
    families.length || pathOwner || integrityTopologies.length;
  return {
    schema: 'kungfu.maintainability-task-graph/v1',
    verdict: graphResolved ? 'pass' : 'unresolved',
    query,
    authoritySemantics: report.authoritySemantics,
    owner: pathOwner || [...new Set(families.map((family) => family.owner))],
    families: families.map((family) => {
      const projections = family.surfaces.filter((surface) =>
        ['generated-projection', 'thin-binding'].includes(surface.role),
      );
      return {
        id: family.id,
        authority: family.authority,
        projections,
        compatibilityReaders: family.surfaces.filter(
          (surface) => surface.role === 'compatibility-reader',
        ),
        likelyWriteSet: [
          ...family.authority.sources,
          ...projections.map((surface) => surface.path),
        ],
        affectedTests: family.surfaces.filter((surface) =>
          ['test', 'conformance-oracle'].includes(surface.role),
        ),
        qualification: family.surfaces.filter(
          (surface) => surface.role === 'package-release',
        ),
        documentation: family.surfaces.filter(
          (surface) => surface.role === 'documentation',
        ),
        knownLimits: family.knownLimits,
        recovery: family.recovery,
      };
    }),
    integrityTopologies: integrityTopologies.map((topology) => ({
      id: topology.id,
      owner: topology.owner,
      authority: topology.authority,
      legalAxes: topology.legalAxes,
      adapters: topology.adapters,
      projections: topology.projections,
      qualification: topology.qualification,
      exceptions: topology.exceptions,
      findings: (report.integrity?.findings || []).filter(
        (finding) => finding.topology === topology.id,
      ),
      recovery: topology.recovery,
    })),
    productionBoundaries: report.productionBoundaries,
    nextActions:
      families.length || integrityTopologies.length
        ? [
            'edit the existing authority route, not this navigation projection',
            'regenerate or validate every declared projection',
            'run affected tests, qualification, documentation, and known-limit checks independently',
          ]
        : [
            'query a repository path, semantic family id, schema id, symbol, capability, or exact error token',
          ],
  };
}

function parseArgs(argv) {
  const options = {
    write: false,
    check: false,
    json: false,
    query: '',
    legacyReportCheck: false,
    electronBuilderConfigWrite: false,
    electronBuilderConfigCheck: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--') continue;
    if (arg === '--write') options.write = true;
    else if (arg === '--check') options.check = true;
    else if (arg === '--json') options.json = true;
    else if (arg === '--query') options.query = argv[++index] || '';
    else if (arg === '--check-legacy-report') options.legacyReportCheck = true;
    else if (arg === '--electron-builder-config-write')
      options.electronBuilderConfigWrite = true;
    else if (arg === '--electron-builder-config-check')
      options.electronBuilderConfigCheck = true;
    else throw new Error(`unknown argument '${arg}'`);
  }
  if (options.write && options.check)
    throw new Error('--write and --check are mutually exclusive');
  return options;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.electronBuilderConfigWrite) {
    writeElectronBuilderProjections();
    return;
  }
  if (options.electronBuilderConfigCheck) {
    checkElectronBuilderProjections();
    return;
  }
  if (options.check) checkElectronBuilderProjections();
  const manifest = readJson(MANIFEST_PATH);
  const layers = readJson('framework/core/architecture/layers.json');
  const report = buildReport(manifest, layers);
  if (options.query) {
    const taskGraph = queryTaskGraph(report, manifest, options.query, layers);
    process.stdout.write(`${JSON.stringify(taskGraph, null, 2)}\n`);
    if (taskGraph.verdict === 'unresolved') process.exitCode = 3;
    return;
  }
  const target = path.join(ROOT, manifest.legacyReportPath);
  if (options.write) {
    if (report.issues.length)
      throw new Error('refusing to write a report with blocking issues');
    fs.writeFileSync(target, `${JSON.stringify(report, null, 2)}\n`);
  } else if (options.legacyReportCheck) {
    if (!fs.existsSync(target))
      throw new Error(`missing legacy report ${manifest.legacyReportPath}`);
    const expected = `${JSON.stringify(report, null, 2)}\n`;
    if (fs.readFileSync(target, 'utf8') !== expected)
      throw new Error(
        `stale legacy report ${manifest.legacyReportPath}; live checks regenerate an isolated exact-revision projection`,
      );
  }
  if (options.json)
    process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  else
    process.stdout.write(
      `${report.verdict}: ${report.schema}; families=${report.summary.families}; surfaces=${report.summary.mappedSurfaces}; issues=${report.summary.blockingIssues}\n`,
    );
  if (report.issues.length) process.exitCode = 1;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    main();
  } catch (error) {
    process.stderr.write(
      `semantic amplification: ${error instanceof Error ? error.message : String(error)}\n`,
    );
    process.exitCode = 2;
  }
}

