const fs = require('node:fs');
const path = require('node:path');

const rootDir = path.dirname(__dirname);
const authorityPath = path.join(rootDir, 'node-api-authority.json');
const authority = JSON.parse(fs.readFileSync(authorityPath, 'utf8'));
const exportsByCategory = authority.categories;
const names = Object.values(exportsByCategory).flat().sort();
const uniqueNames = new Set(names);

if (uniqueNames.size !== names.length) {
  throw new Error(
    'node-api-authority.json classifies an export more than once',
  );
}

const generated = [
  '// SPDX-License-Identifier: Apache-2.0',
  '',
  '// Generated by .gyp/generate-node-api-types.js from node-api-authority.json.',
  '// Do not edit this file directly.',
  '',
  'export interface NativeExportSurface {',
  ...names.map((name) => `  readonly ${name}: unknown;`),
  '}',
  '',
].join('\n');
const outputPath = path.join(rootDir, authority.generatedDeclaration);

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath)) {
    throw new Error(
      `missing generated declaration ${authority.generatedDeclaration}`,
    );
  }
  if (fs.readFileSync(outputPath, 'utf8') !== generated) {
    throw new Error(
      `${authority.generatedDeclaration} is stale; run npm run generate:node-api-types`,
    );
  }
} else {
  fs.writeFileSync(outputPath, generated);
}
