import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';

const ROOT = path.resolve(import.meta.dirname, '..');
const ASSETS = path.join(
  ROOT,
  'framework/core/src/python/kungfu/kfx_authoring_assets',
);
const AGENT_BRIEF = path.join(
  ROOT,
  'framework/core/src/python/kungfu/agent/kfx-authoring.md',
);
const SOURCE = path.join(ROOT, 'framework/api/src/capability/service-authz.ts');
const API = JSON.parse(
  readFileSync(path.join(ROOT, 'framework/api/package.json'), 'utf8'),
);
const KFX = JSON.parse(
  readFileSync(path.join(ROOT, 'framework/kfx/package.json'), 'utf8'),
);
const NATIVE = JSON.parse(
  readFileSync(
    path.join(ROOT, 'framework/kfx/kungfu-kfx.contract.json'),
    'utf8',
  ),
);
if (!API.version || API.version !== KFX.version) {
  throw new Error('public KFX and API package versions must match');
}
const PRODUCT_VERSION = KFX.version;
const GENERATED = [
  'kfx-host.d.ts',
  'sandbox-launcher.d.ts',
  'service-authz.d.ts',
  'service-webhook-host.mjs',
  'types.d.ts',
];

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function canonical(value) {
  if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
  if (value && typeof value === 'object') {
    return `{${Object.entries(value)
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([key, child]) => `${JSON.stringify(key)}:${canonical(child)}`)
      .join(',')}}`;
  }
  return JSON.stringify(value);
}

function semanticRoot(value) {
  return `sha256:${sha256(Buffer.from(canonical(value)))}`;
}

function filesBelow(root) {
  const rows = [];
  function walk(current) {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const absolute = path.join(current, entry.name);
      if (entry.isDirectory()) walk(absolute);
      else if (entry.isFile())
        rows.push(path.relative(root, absolute).split(path.sep).join('/'));
    }
  }
  walk(root);
  return rows.sort();
}

function formatGenerated(name, contents) {
  const normalized = name.endsWith('.d.ts')
    ? contents.toString('utf8').replace(/\nexport \{\};\n?$/u, '\n')
    : contents;
  const result = spawnSync(
    'pnpm',
    ['exec', 'biome', 'format', '--stdin-file-path', name],
    { cwd: ROOT, encoding: 'utf8', input: normalized },
  );
  if (result.status !== 0) {
    throw new Error(
      result.stderr || result.stdout || `Biome failed for ${name}`,
    );
  }
  return result.stdout;
}

function projectPublicDeclaration(name, contents) {
  if (name !== 'types.d.ts') return contents;
  const internalStorageHelper =
    / {2}runStorageServiceOperation\?: \(\n(?: {4}.*\n)+? {2}\) => Record<string, unknown>;\n/u;
  const projected = contents.replace(internalStorageHelper, '');
  if (projected === contents) {
    throw new Error(
      'KFX authoring SDK projection could not remove the internal storage helper',
    );
  }
  if (/runStorageServiceOperation/u.test(projected)) {
    throw new Error(
      'KFX authoring SDK projection exposes the internal storage helper',
    );
  }
  return projected;
}

function compileSdk(destination) {
  const js = mkdtempSync(path.join(os.tmpdir(), 'kungfu-kfx-authoring-js-'));
  const types = mkdtempSync(
    path.join(os.tmpdir(), 'kungfu-kfx-authoring-types-'),
  );
  const common = [
    '--filter',
    '@kungfu-tech/api',
    'exec',
    'tsc',
    'src/capability/service-authz.ts',
    '--target',
    'ES2022',
    '--module',
    'NodeNext',
    '--moduleResolution',
    'NodeNext',
    '--skipLibCheck',
  ];
  try {
    for (const args of [
      [...common, '--outDir', js],
      [...common, '--declaration', '--emitDeclarationOnly', '--outDir', types],
    ]) {
      const result = spawnSync('pnpm', args, { cwd: ROOT, encoding: 'utf8' });
      if (result.status !== 0) {
        throw new Error(
          result.stderr || result.stdout || 'TypeScript projection failed',
        );
      }
    }
    mkdirSync(destination, { recursive: true });
    const marker = Buffer.from(
      '// @generated by scripts/generate-kfx-authoring-kit.mjs source_path=framework/api/src/capability/service-authz.ts\n',
    );
    writeFileSync(
      path.join(destination, 'service-webhook-host.mjs'),
      formatGenerated(
        'service-webhook-host.mjs',
        Buffer.concat([
          marker,
          readFileSync(path.join(js, 'service-authz.js')),
        ]),
      ),
    );
    for (const name of GENERATED.filter((value) => value.endsWith('.d.ts'))) {
      const declaration = formatGenerated(
        name,
        Buffer.concat([marker, readFileSync(path.join(types, name))]),
      );
      writeFileSync(
        path.join(destination, name),
        projectPublicDeclaration(name, declaration),
      );
    }
  } finally {
    rmSync(js, { recursive: true, force: true });
    rmSync(types, { recursive: true, force: true });
  }
}

function buildContract(assetRoot) {
  const sdkFiles = [...GENERATED].sort();
  const sdkRoots = Object.fromEntries(
    sdkFiles.map((name) => [
      name,
      sha256(readFileSync(path.join(assetRoot, 'sdk', name))),
    ]),
  );
  const templateRoot = path.join(assetRoot, 'templates/webhook-service');
  const templateFiles = filesBelow(templateRoot);
  const templateRoots = Object.fromEntries(
    templateFiles.map((name) => [
      name,
      sha256(readFileSync(path.join(templateRoot, name))),
    ]),
  );
  const coordinates = filesBelow(assetRoot)
    .filter(
      (relative) => relative !== '__init__.py' && relative !== 'contract.json',
    )
    .filter(
      (relative) =>
        !relative.startsWith('__pycache__/') &&
        !relative.includes('/__pycache__/') &&
        !relative.endsWith('.pyc'),
    )
    .map((relative) => {
      const payload = readFileSync(path.join(assetRoot, relative));
      return { path: relative, sha256: sha256(payload), bytes: payload.length };
    });
  const sourceRoot = `sha256:${sha256(readFileSync(SOURCE))}`;
  const sdk = {
    schema: 'kungfu.kfx-authoring-sdk-projection/v1',
    productVersion: PRODUCT_VERSION,
    apiVersion: API.version,
    kfxVersion: KFX.version,
    source: 'framework/api/src/capability/service-authz.ts',
    sourceRoot,
    files: sdkFiles,
    roots: sdkRoots,
  };
  sdk.root = semanticRoot(sdk);
  const webhookService = {
    id: 'webhook-service',
    files: templateFiles,
    roots: templateRoots,
  };
  webhookService.root = semanticRoot(webhookService);
  const body = {
    schema: 'kungfu.kfx-authoring-kit/v1',
    version: 1,
    productVersion: PRODUCT_VERSION,
    nativeKfx: {
      contractVersion: NATIVE.version,
      serviceHostSchema: NATIVE.nativeRuntime.serviceHost.schema,
      receiptSchema: NATIVE.nativeRuntime.serviceHost.receiptSchema,
    },
    sdk,
    schemas: {
      packageManifest: 'kungfu.kfx.manifest/v1',
      serviceHost: NATIVE.nativeRuntime.serviceHost.schema,
      serviceReceipt: NATIVE.nativeRuntime.serviceHost.receiptSchema,
    },
    templates: { webhookService },
    lifecycle: [
      'inspect',
      'scaffold',
      'validate',
      'build',
      'qualify',
      'package',
      'native-plan',
      'authorize',
      'install',
      'activate',
      'run',
      'observe',
      'diagnose',
      'deactivate',
      'rollback',
      'upgrade',
      'uninstall',
    ],
    commands: {
      brief: 'kungfu kfx author brief',
      capabilities: 'kungfu kfx author capabilities --json',
      scaffold: 'kungfu kfx author scaffold <key> --out <dir> --execute --json',
      inspect: 'kungfu kfx author inspect <dir> --json',
      validate: 'kungfu kfx author validate <dir> --json',
      build: 'kungfu kfx author build <dir> --out <build-dir> --execute --json',
      qualify: 'kungfu kfx author qualify <dir> --json',
      package:
        'kungfu kfx author package <dir> --out <package.tgz> --execute --json',
      nativePlan: 'kungfu kfx native plan --root workspace=<dir>',
      nativeStatus: 'kungfu kfx native status --root workspace=<dir>',
      nativeHistory: 'kungfu kfx native history --package-key <key>',
    },
    nonClaims: [
      'authoring-does-not-grant-capabilities',
      'authoring-does-not-issue-warrant-or-passport',
      'qualification-does-not-install-or-activate',
      'loopback-fixture-does-not-prove-production-network-admission',
      'source-or-schema-validity-does-not-prove-kfd-or-release-readiness',
    ],
    files: coordinates,
  };
  return { ...body, contractRoot: semanticRoot(body) };
}

function materialize(target) {
  mkdirSync(path.join(target, 'sdk'), { recursive: true });
  compileSdk(path.join(target, 'sdk'));
  const contract = buildContract(target);
  writeFileSync(
    path.join(target, 'contract.json'),
    `${JSON.stringify(contract, null, 2)}\n`,
  );
}

function compare(expectedRoot, actualRoot) {
  const relative = ['contract.json', ...GENERATED.map((name) => `sdk/${name}`)];
  const drift = relative.filter((name) => {
    const expected = path.join(expectedRoot, name);
    const actual = path.join(actualRoot, name);
    return (
      !existsSync(expected) ||
      !existsSync(actual) ||
      !readFileSync(expected).equals(readFileSync(actual))
    );
  });
  if (drift.length)
    throw new Error(`KFX authoring kit drift: ${drift.join(', ')}`);
}

const mode = process.argv[2] ?? '--check';
if (mode === '--write') {
  materialize(ASSETS);
  cpSync(path.join(ASSETS, 'brief.md'), AGENT_BRIEF);
  process.stdout.write(
    `${path.relative(ROOT, path.join(ASSETS, 'contract.json'))}\n`,
  );
} else if (mode === '--check') {
  const temporary = mkdtempSync(
    path.join(os.tmpdir(), 'kungfu-kfx-authoring-kit-'),
  );
  try {
    cpSync(path.join(ASSETS, 'brief.md'), path.join(temporary, 'brief.md'));
    cpSync(path.join(ASSETS, 'templates'), path.join(temporary, 'templates'), {
      recursive: true,
    });
    materialize(temporary);
    compare(ASSETS, temporary);
    if (
      !readFileSync(AGENT_BRIEF).equals(
        readFileSync(path.join(temporary, 'brief.md')),
      )
    ) {
      throw new Error('KFX authoring Agent Brief drift');
    }
    process.stdout.write('KFX authoring kit is current\n');
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
} else {
  throw new Error(
    'usage: node scripts/generate-kfx-authoring-kit.mjs [--check|--write]',
  );
}
