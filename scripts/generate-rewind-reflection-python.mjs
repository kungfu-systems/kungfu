import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(
  ROOT,
  'framework/core/src/python/kungfu/rewind/reflection.fbs',
);
const TARGET = path.join(
  ROOT,
  'framework/core/src/python/kungfu/rewind/reflection',
);
const FACADE = path.join(
  ROOT,
  'framework/core/src/python/kungfu/rewind/reflection_fb.py',
);
const BINARY_SCHEMA = path.join(
  ROOT,
  'framework/core/src/python/kungfu/rewind/reflection.bfbs',
);
const MODULES = [
  'AdvancedFeatures',
  'BaseType',
  'Enum',
  'EnumVal',
  'Field',
  'KeyValue',
  'Object',
  'RPCCall',
  'Schema',
  'SchemaFile',
  'Service',
  'Type',
];

function argument(name) {
  const index = process.argv.indexOf(name);
  return index < 0 ? '' : process.argv[index + 1] || '';
}

function facadeSource() {
  const imports = MODULES.map(
    (name) =>
      `from kungfu.rewind.reflection import ${name} as _${name}  # noqa: E402`,
  ).join('\n');
  const modules = MODULES.map((name) => `    _${name},`).join('\n');
  return `# automatically generated by scripts/generate-rewind-reflection-python.mjs
# source: framework/core/src/python/kungfu/rewind/reflection.fbs
# do not modify

"""Compatibility facade for the split FlatBuffers reflection projection."""

import sys

from kungfu.rewind import reflection as _reflection

# flatc emits imports rooted at the declared \`\`reflection\`\` namespace. Keep
# the generated modules byte-for-byte canonical while resolving that namespace
# to their package-qualified installation location.
sys.modules["reflection"] = _reflection

${imports}


def _export_legacy_surface(module):
    prefix = module.__name__.rsplit(".", 1)[-1]
    for name, value in vars(module).items():
        if name == prefix or name.startswith(prefix):
            value.__module__ = __name__
            globals()[name] = value


for _module in (
${modules}
):
    _export_legacy_surface(_module)

# Static aliases keep the typed public consumers visible to mypy while the
# complete legacy surface remains projected by the generated-name loop above.
BaseType = _BaseType.BaseType
Schema = _Schema.Schema

# These names were also visible on flatc's former one-file module.
flatbuffers = _Schema.flatbuffers
import_numpy = _Schema.import_numpy
np = _Schema.np
`;
}

const flatc = argument('--flatc') || process.env.KUNGFU_FLATC || 'flatc';
const check = process.argv.includes('--check');
const version = spawnSync(flatc, ['--version'], { encoding: 'utf8' });
if (version.status !== 0 || version.stdout.trim() !== 'flatc version 25.9.23') {
  throw new Error(`expected flatc 25.9.23 at ${flatc}`);
}

const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'kungfu-reflection-'));
try {
  const generated = spawnSync(flatc, ['--python', '-o', temporary, SOURCE], {
    encoding: 'utf8',
  });
  if (generated.status !== 0) throw new Error(generated.stderr.trim());
  const generatedRoot = path.join(temporary, 'reflection');
  const binary = spawnSync(flatc, ['-b', '--schema', '-o', temporary, SOURCE], {
    encoding: 'utf8',
  });
  if (binary.status !== 0) throw new Error(binary.stderr.trim());
  const generatedBinary = path.join(temporary, 'reflection.bfbs');
  const files = [...MODULES.map((name) => `${name}.py`), '__init__.py'];
  if (check) {
    for (const name of files) {
      const expected = fs.readFileSync(path.join(generatedRoot, name));
      const actual = fs.readFileSync(path.join(TARGET, name));
      if (!expected.equals(actual)) throw new Error(`${name} is stale`);
    }
    if (fs.readFileSync(FACADE, 'utf8') !== facadeSource()) {
      throw new Error('reflection_fb.py is stale');
    }
    if (
      !fs.readFileSync(BINARY_SCHEMA).equals(fs.readFileSync(generatedBinary))
    )
      throw new Error('reflection.bfbs is stale');
  } else {
    fs.mkdirSync(TARGET, { recursive: true });
    for (const name of files) {
      fs.copyFileSync(path.join(generatedRoot, name), path.join(TARGET, name));
    }
    fs.writeFileSync(FACADE, facadeSource());
    fs.copyFileSync(generatedBinary, BINARY_SCHEMA);
  }
} finally {
  fs.rmSync(temporary, { recursive: true, force: true });
}

console.log(
  `[rewind-reflection] ${check ? 'current' : 'generated'} with flatc 25.9.23`,
);
